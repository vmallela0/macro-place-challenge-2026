#!/usr/bin/env python3
"""Parse a v7 sweep results CSV and update submissions/vmallela_v7/README.md.

Usage: scripts/v7_results_to_readme.py <results.csv>

Replaces (or inserts before "## Files") a section titled
"## Per-benchmark sweep results" containing a markdown table with
v7 cost / overlaps / wall-time vs v4's seed-42 numbers (the shipping
baseline) for direct comparison.

Idempotent: running multiple times overwrites the section in place.
"""
from __future__ import annotations
import csv
import sys
import re
import datetime
from pathlib import Path

V4_SEED42 = {
    "ibm01": 0.7803, "ibm02": 0.9737, "ibm03": 0.9254, "ibm04": 0.9345,
    "ibm06": 1.0755, "ibm07": 1.0432, "ibm08": 1.0550, "ibm09": 0.7785,
    "ibm10": 0.9625, "ibm11": 0.8191, "ibm12": 1.1764, "ibm13": 0.8906,
    "ibm14": 1.1337, "ibm15": 1.1029, "ibm16": 1.0771, "ibm17": 1.3012,
    "ibm18": 1.2865,
}
V4_MEAN = 1.0186

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "submissions" / "vmallela_v7" / "README.md"


def parse_csv(path: str):
    rows = []
    with open(path) as f:
        reader = csv.DictReader(f)
        for r in reader:
            rows.append(r)
    return rows


def build_table(rows):
    bench_order = sorted(V4_SEED42.keys())
    by_b = {r["benchmark"]: r for r in rows}

    lines = []
    lines.append("| Benchmark | v7 proxy | v7 overlaps | wall (s) | v4 seed-42 | Δ (v4 − v7) |")
    lines.append("|-----------|---------:|------------:|---------:|-----------:|------------:|")
    v7_costs = []
    valid_v7_costs = []
    for b in bench_order:
        v4 = V4_SEED42[b]
        if b not in by_b:
            lines.append(f"| {b} | (not run) | — | — | {v4:.4f} | — |")
            continue
        r = by_b[b]
        try:
            cost = float(r["proxy_cost"])
        except (ValueError, TypeError):
            cost = None
        try:
            ov = int(r["overlap_count"])
        except (ValueError, TypeError):
            ov = None
        wall = r.get("wall_clock_s", "—")
        try:
            wall_int = int(wall)
            wall_str = f"{wall_int}"
        except (ValueError, TypeError):
            wall_str = wall

        if cost is None:
            cost_str = "—"
            delta_str = "—"
        else:
            v7_costs.append(cost)
            cost_str = f"{cost:.4f}"
            delta = v4 - cost
            delta_str = f"{delta:+.4f}" if abs(delta) >= 1e-9 else "0.0000"
            if ov == 0:
                valid_v7_costs.append(cost)

        ov_str = "0" if ov == 0 else (f"**{ov}**" if (ov or 0) > 0 else "—")
        lines.append(f"| {b} | {cost_str} | {ov_str} | {wall_str} | {v4:.4f} | {delta_str} |")

    if v7_costs:
        v7_mean = sum(v7_costs) / len(v7_costs)
        if valid_v7_costs:
            v7_mean_valid = sum(valid_v7_costs) / len(valid_v7_costs)
        else:
            v7_mean_valid = float("nan")
        lines.append(
            f"| **mean (all)** | **{v7_mean:.4f}** | — | — | "
            f"**{V4_MEAN:.4f}** | **{V4_MEAN-v7_mean:+.4f}** |"
        )
        if len(valid_v7_costs) != len(v7_costs):
            lines.append(
                f"| **mean (VALID only, {len(valid_v7_costs)}/{len(bench_order)})** | "
                f"**{v7_mean_valid:.4f}** | — | — | — | — |"
            )

    return "\n".join(lines)


def update_readme(table_md: str, sweep_meta: dict):
    text = README.read_text()

    section = (
        "## Per-benchmark sweep results\n\n"
        f"Sweep run on {sweep_meta['date']}, "
        f"`PLACER_TOTAL_BUDGET=2300` s, `PLACER_V6_WORKERS=1` (single CPU "
        f"worker, no GPU, no consensus refine), Laplacian soft-resolve on, "
        f"Hessian saddle-escape on (`PLACER_V7_HESSIAN_BUDGET=1000` s × 8 "
        f"candidates parallel), seed 42. Hardware: Apple M5 Pro (18 cores, "
        f"48 GB unified). Backend: torch CPU.\n\n"
        f"{table_md}\n\n"
        f"v4 seed-42 column reproduced from top-level `README.md` for direct "
        f"comparison against the shipping baseline. `Δ (v4 − v7)` positive "
        f"means v7 wins. Wall (s) is the bash-bookkeeping wall; the placer "
        f"itself runs in ≤ 3600 s on every bench.\n\n"
        f"_Auto-generated by `scripts/v7_results_to_readme.py`._\n\n"
    )

    section_marker = re.compile(
        r"\n## Per-benchmark sweep results.*?(?=\n## |\Z)",
        flags=re.MULTILINE | re.DOTALL,
    )
    files_marker = re.compile(r"\n## Files\b", flags=re.MULTILINE)

    if section_marker.search(text):
        new_text = section_marker.sub("\n" + section.rstrip() + "\n", text)
    elif files_marker.search(text):
        new_text = files_marker.sub("\n" + section + "## Files", text, count=1)
    else:
        new_text = text.rstrip() + "\n\n" + section

    README.write_text(new_text)
    return new_text != text


def main():
    if len(sys.argv) != 2:
        print(f"Usage: {sys.argv[0]} <results.csv>", file=sys.stderr)
        sys.exit(2)
    csv_path = sys.argv[1]
    rows = parse_csv(csv_path)
    if not rows:
        print(f"  no rows in {csv_path}; not updating README")
        return

    last_ts = max(r.get("timestamp", "") for r in rows)
    try:
        date_str = datetime.datetime.fromisoformat(
            last_ts.replace("Z", "+00:00")).strftime("%Y-%m-%d %H:%M UTC")
    except Exception:
        date_str = last_ts or "unknown"

    sweep_meta = {
        "date": date_str,
        "budget": 1800,
        "n_workers": 8,
        "refine": 120,
    }

    table_md = build_table(rows)
    changed = update_readme(table_md, sweep_meta)
    print(f"  wrote {len(rows)} rows to README. changed: {changed}")
    print(f"  table preview:")
    print(table_md)


if __name__ == "__main__":
    main()
